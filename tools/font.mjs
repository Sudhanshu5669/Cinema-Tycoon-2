for (const [k, v] of Object.entries(FONT)) {
  if (v.length !== 15) throw new Error(`font glyph "${k}" is ${v.length} cells, expected 15`);
}

export const CHAR_W = 3, CHAR_H = 5;

export function drawText(bmp, text, x, y, scale, color) {
  let cx = x;
  for (const raw of String(text).toUpperCase()) {
    const g = FONT[raw] ?? FONT[' '];
    for (let row = 0; row < CHAR_H; row++) {
      for (let col = 0; col < CHAR_W; col++) {
        if (g[row * CHAR_W + col] !== '#') continue;
        for (let oy = 0; oy < scale; oy++)
          for (let ox = 0; ox < scale; ox++)
            bmp.set(cx + col * scale + ox, y + row * scale + oy, color);
      }
    }
    cx += (CHAR_W + 1) * scale;
  }
  return cx;
}

export const textWidth = (t, s) => String(t).length * (CHAR_W + 1) * s - s;
